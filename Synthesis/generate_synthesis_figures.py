"""Draw the figures of the speech synthesis chapter.

Writes SVG files to attachments/ next to this script:
  - synthesis_pipelines.svg: how the blocks of a TTS system have been merged over time
  - synthesis_timeline.svg: approximate timeline of synthesis methods
  - length_regulator.svg: how a duration model expands phonemes to frames
  - codec_language_model.svg: speech tokens generated by a codec language model

Only needs matplotlib. For previews in another format:
  python generate_synthesis_figures.py <output folder> png
"""
import os
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.patches import FancyBboxPatch, FancyArrowPatch

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "attachments")
EXT = "svg"

BLUE = "#46A5FF"
RED = "#FD6360"
GREY = "#555555"
LIGHT = "#E8E8E8"


def box(ax, x, y, w, h, text, colour, fontsize=9):
    """Rounded box with centred text. (x, y) is the centre."""
    ax.add_patch(FancyBboxPatch((x - w / 2, y - h / 2), w, h,
                                boxstyle="round,pad=0.02,rounding_size=0.08",
                                facecolor=colour, edgecolor="none", alpha=0.9))
    ax.text(x, y, text, ha="center", va="center", fontsize=fontsize,
            color="white" if colour in (BLUE, RED, GREY) else "black")


def arrow(ax, x0, x1, y, label=None):
    ax.add_patch(FancyArrowPatch((x0, y), (x1, y), arrowstyle="-|>",
                                 mutation_scale=10, color="#333333", lw=1))
    if label:
        ax.text((x0 + x1) / 2, y + 0.2, label, ha="center", va="bottom",
                fontsize=7.5, color="#333333", style="italic")


def pipelines():
    """One row per system type. Blocks drawn as boxes, data as arrow labels."""
    rows = [
        ("Unit selection\n(1990s–2010s)",
         [("Text\nanalysis", LIGHT), ("Unit selection\nand joining", GREY)],
         ["linguistic\nfeatures"]),
        ("Statistical parametric\n(2000s–2010s)",
         [("Text\nanalysis", LIGHT), ("Acoustic model\n(HMM, DNN)", BLUE),
          ("Vocoder\n(source-filter)", RED)],
         ["linguistic\nfeatures", "vocoder\nfeatures"]),
        ("Neural, two-stage\n(2017–)",
         [("Text\nanalysis", LIGHT), ("Neural\nacoustic model", BLUE),
          ("Neural\nvocoder", RED)],
         ["phonemes or\ncharacters", "mel\nspectrogram"]),
        ("Neural, end-to-end\n(2021–)",
         [("Text\nanalysis", LIGHT), ("One network:\ntext to waveform", BLUE)],
         ["phonemes or\ncharacters"]),
        ("Codec language model\n(2023–)",
         [("Tokenisers:\ntext + voice prompt", LIGHT), ("Language\nmodel", BLUE),
          ("Codec\ndecoder", RED)],
         ["tokens", "speech\ntokens"]),
    ]
    fig, ax = plt.subplots(figsize=(12, 6.2))
    x_label, x_in, x_out = -0.2, 1.3, 12.0
    for r, (name, blocks, data) in enumerate(rows):
        y = -1.25 * r
        ax.text(x_label, y, name, ha="right", va="center", fontsize=9.5,
                fontweight="bold")
        ax.text(x_in, y, "Text", ha="center", va="center", fontsize=9)
        n = len(blocks)
        # Spread blocks between the input and the output.
        span = x_out - x_in - 1.6
        w = min(2.0, span / n - 1.2)
        xs = [x_in + 0.8 + span * (k + 0.5) / n for k in range(n)]
        if n == 2 and "One network" in blocks[1][0]:
            w = 2.0
        arrow(ax, x_in + 0.35, xs[0] - w / 2 - 0.05, y)
        for k, ((label, colour), xc) in enumerate(zip(blocks, xs)):
            box(ax, xc, y, w, 0.75, label, colour)
            if k + 1 < n:
                arrow(ax, xc + w / 2 + 0.05, xs[k + 1] - w / 2 - 0.05, y,
                      data[k])
        arrow(ax, xs[-1] + w / 2 + 0.05, x_out - 0.45, y)
        ax.text(x_out, y, "Speech", ha="center", va="center", fontsize=9)
    ax.set_xlim(-2.6, 12.6)
    ax.set_ylim(-1.25 * (len(rows) - 1) - 0.7, 0.8)
    ax.axis("off")
    fig.tight_layout()
    out = os.path.join(OUT, "synthesis_pipelines." + EXT)
    fig.savefig(out, bbox_inches="tight")
    plt.close(fig)
    print("Wrote", out)


def timeline():
    """Eras as horizontal bars, milestones as labelled ticks. Dates are approximate."""
    eras = [
        ("Formant and articulatory synthesis", 1960, 2000, GREY),
        ("Diphone concatenation", 1985, 2000, GREY),
        ("Unit selection", 1996, 2018, GREY),
        ("HMM-based statistical parametric", 1999, 2017, BLUE),
        ("Neural acoustic models and vocoders", 2016, 2026, BLUE),
        ("Large-scale and zero-shot", 2023, 2026, RED),
    ]
    # (year, label, level): level staggers labels that are close in time.
    milestones = [
        (1980, "Klatt formant\nsynthesiser", 0),
        (1996, "Unit selection\n(Hunt & Black)", 0),
        (2005, "First Blizzard\nChallenge", 0),
        (2016, "WaveNet", 0),
        (2018, "Tacotron 2", 1),
        (2021, "VITS", 2),
        (2023, "VALL-E", 3),
    ]
    fig, ax = plt.subplots(figsize=(11, 5))
    for k, (name, start, end, colour) in enumerate(eras):
        y = -k
        ax.barh(y, end - start, left=start, height=0.6, color=colour,
                alpha=0.85, edgecolor="none")
        if end - start > 14:
            ax.text(start + 0.5, y, name, ha="left", va="center",
                    fontsize=9, color="white")
        else:
            ax.text(start - 0.5, y, name, ha="right", va="center",
                    fontsize=9)
    y_ms = 1.2
    for year, label, level in milestones:
        top = y_ms + 0.05 + 0.4 * level
        ax.plot([year, year], [y_ms - 0.25, top], color="#333333", lw=1)
        ax.text(year, top + 0.1, label, ha="center" if level == 0 else "left",
                va="bottom", fontsize=8)
    ax.axhline(y_ms - 0.25, color="#333333", lw=1)
    ax.set_xlim(1958, 2027)
    ax.set_ylim(-len(eras) + 0.4, y_ms + 2.6)
    ax.set_yticks([])
    for side in ("left", "right", "top"):
        ax.spines[side].set_visible(False)
    ax.set_xticks(range(1960, 2030, 10))
    ax.tick_params(axis="x", labelsize=9)
    fig.tight_layout()
    out = os.path.join(OUT, "synthesis_timeline." + EXT)
    fig.savefig(out, bbox_inches="tight")
    plt.close(fig)
    print("Wrote", out)


def length_regulator():
    """Phoneme states repeated according to predicted durations (FastSpeech)."""
    phonemes = ["h", "ə", "l", "oʊ"]
    durations = [2, 3, 4, 6]
    colours = [BLUE, RED, GREY, "#8BC34A"]
    fig, ax = plt.subplots(figsize=(10, 3.4))
    n_frames = sum(durations)
    # Phoneme row, centred above the frames it covers.
    start = 0
    for p, d, c in zip(phonemes, durations, colours):
        xc = start + d / 2
        box(ax, xc, 2.4, 0.9, 0.6, p, c, fontsize=12)
        ax.text(xc, 1.75, f"duration {d}", ha="center", va="center",
                fontsize=8.5, color="#333333")
        for k in range(d):
            ax.add_patch(FancyArrowPatch((xc, 1.55), (start + k + 0.5, 0.75),
                                         arrowstyle="-|>", mutation_scale=7,
                                         color=c, lw=0.8, alpha=0.7))
            box(ax, start + k + 0.5, 0.45, 0.8, 0.5, "", c)
        start += d
    ax.text(-0.4, 2.4, "Phonemes\n(encoder states)", ha="right", va="center",
            fontsize=9.5)
    ax.text(-0.4, 0.45, "Frames\n(to the decoder)", ha="right", va="center",
            fontsize=9.5)
    ax.text(n_frames / 2, -0.15, "time →", ha="center", va="top", fontsize=9)
    ax.set_xlim(-3.2, n_frames + 0.3)
    ax.set_ylim(-0.5, 2.9)
    ax.axis("off")
    fig.tight_layout()
    out = os.path.join(OUT, "length_regulator." + EXT)
    fig.savefig(out, bbox_inches="tight")
    plt.close(fig)
    print("Wrote", out)


def codec_language_model():
    """Grid of codec tokens: codebooks (rows) over frames (columns)."""
    n_books, n_prompt, n_gen = 4, 5, 9
    fig, ax = plt.subplots(figsize=(11, 3.8))
    x0 = 0
    for f in range(n_prompt + n_gen):
        for b in range(n_books):
            y = n_books - 1 - b
            if f < n_prompt:
                colour = LIGHT
            elif b == 0:
                colour = BLUE
            else:
                colour = RED
            box(ax, x0 + f + 0.5, y + 0.5, 0.82, 0.78, "", colour)
    # Labels for the codebooks.
    for b in range(n_books):
        ax.text(-0.2, n_books - 1 - b + 0.5, f"codebook {b + 1}", ha="right",
                va="center", fontsize=9)
    # Braces as plain text labels above the grid.
    ax.text(n_prompt / 2, n_books + 0.25, "voice prompt\n(tokens of a short recording)",
            ha="center", va="bottom", fontsize=9)
    ax.text(n_prompt + n_gen / 2, n_books + 0.25,
            "generated speech for the new text", ha="center", va="bottom",
            fontsize=9)
    ax.plot([n_prompt, n_prompt], [-0.1, n_books + 0.15], color="#333333",
            lw=1, ls="--")
    # Autoregressive arrows along the first codebook.
    for f in range(n_prompt, n_prompt + n_gen - 1):
        ax.add_patch(FancyArrowPatch((f + 0.75, n_books - 0.5),
                                     (f + 1.25, n_books - 0.5),
                                     arrowstyle="-|>", mutation_scale=7,
                                     color="#333333", lw=0.8))
    ax.text(n_prompt + n_gen + 0.3, n_books - 0.5,
            "one token at a time\n(autoregressive)", ha="left", va="center",
            fontsize=8.5)
    ax.text(n_prompt + n_gen + 0.3, (n_books - 1) / 2,
            "all frames at once\n(non-autoregressive)", ha="left",
            va="center", fontsize=8.5)
    ax.text((n_prompt + n_gen) / 2, -0.3, "frames (time) →", ha="center",
            va="top", fontsize=9)
    ax.set_xlim(-2.0, n_prompt + n_gen + 3.2)
    ax.set_ylim(-0.8, n_books + 1.2)
    ax.axis("off")
    fig.tight_layout()
    out = os.path.join(OUT, "codec_language_model." + EXT)
    fig.savefig(out, bbox_inches="tight")
    plt.close(fig)
    print("Wrote", out)


if __name__ == "__main__":
    import sys
    if len(sys.argv) > 1:
        OUT = sys.argv[1]
    if len(sys.argv) > 2:
        EXT = sys.argv[2]
    os.makedirs(OUT, exist_ok=True)
    pipelines()
    timeline()
    length_regulator()
    codec_language_model()
